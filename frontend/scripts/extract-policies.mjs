// Reads the LicenceBackend OpenAPI document and emits runtime constants for
// validation policies (e.g. password min length) so the frontend and backend
// stay in sync from a single source of truth.
//
// Run automatically after `pnpm run orval` (see package.json).

import { writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, '..', 'src', 'api', 'policies.generated.ts');
const openApiUrl = process.env.OPENAPI_URL ?? 'https://localhost:5001/openapi/v1.json';

process.env.NODE_TLS_REJECT_UNAUTHORIZED ??= '0';

const res = await fetch(openApiUrl);
if (!res.ok) {
  console.error(`Failed to fetch OpenAPI doc from ${openApiUrl}: ${res.status}`);
  process.exit(1);
}
const doc = await res.json();

function readString(schemaName, propertyName) {
  const schema = doc?.components?.schemas?.[schemaName];
  const prop = schema?.properties?.[propertyName];
  if (!prop) throw new Error(`Missing ${schemaName}.${propertyName} in OpenAPI doc`);
  if (typeof prop.minLength !== 'number' || typeof prop.maxLength !== 'number') {
    throw new Error(`Missing min/max length on ${schemaName}.${propertyName}`);
  }
  return { minLength: prop.minLength, maxLength: prop.maxLength };
}

const password = readString('CreateUserRequest', 'password');

const banner = '// Generated by scripts/extract-policies.mjs from the OpenAPI document. Do not edit manually.\n';
const body =
  `export const PASSWORD_MIN_LENGTH = ${password.minLength};\n` +
  `export const PASSWORD_MAX_LENGTH = ${password.maxLength};\n`;

await writeFile(outFile, banner + '\n' + body, 'utf8');
console.log(`Wrote ${outFile}: PASSWORD_MIN_LENGTH=${password.minLength}, PASSWORD_MAX_LENGTH=${password.maxLength}`);
